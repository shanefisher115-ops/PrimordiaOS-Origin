import { MissionHub } from "../modules/mission_hub_engine";
import { RealmEvent } from "../realms/realm-events";
import { TelemetryBus } from "../services/telemetry";
import { AMO } from "../amo/amo-core";

export class MissionHubAgent {
  constructor() {
    this.userId = "defaultUser";
    this.lastVelocity = 0;
    this.lastXP = 0;
    this.lastOmega = 0;

    this.start();
  }

  start() {
    // Listen for mission completion
    RealmEvent.on("missionhub.mission.complete", (payload) => {
      this.onMissionComplete(payload);
    });

    // Listen for mission activity telemetry
    TelemetryBus.listen("moneyplughub.mission_activity", (payload) => {
      this.onMissionActivity(payload);
    });

    // Periodic agent loop
    setInterval(() => this.agentLoop(), 1500);

    console.log("[MissionHubAgent] Agent online.");
  }

  // ============================
  // Mission Completion Behavior
  // ============================
  onMissionComplete({ userId, missionId, xp, omega }) {
    console.log(
      `[MissionHubAgent] Mission complete: ${missionId} | XP +${xp} | Ω +${omega}`
    );

    // Reward surge behavior
    if (omega > 10) {
      AMO.fire("missionhub.agent.omega_surge", {
        userId,
        missionId,
        bonus: omega * 0.15
      });
    }

    // Auto‑assign next mission
    const missions = MissionHub.listMissions();
    const next = missions[Math.floor(Math.random() * missions.length)];

    MissionHub.startMission(userId, next.id);

    console.log(`[MissionHubAgent] Auto‑assigned next mission: ${next.id}`);
  }

  // ============================
  // Mission Activity Behavior
  // ============================
  onMissionActivity({ userId, velocity, progress }) {
    this.lastVelocity = velocity;

    // If velocity spikes, trigger AMO micro‑flux
    if (velocity > 0.8) {
      AMO.fire("missionhub.agent.velocity_spike", {
        userId,
        velocity,
        flux: velocity * 0.5
      });
    }
  }

  // ============================
  // Agent Loop (runs every 1.5s)
  // ============================
  agentLoop() {
    const state = MissionHub.getUserState(this.userId);

    // Auto‑boost slow missions
    if (state.active && state.velocity < 0.2) {
      MissionHub.updateProgress(this.userId, 0.1);
      console.log("[MissionHubAgent] Boosting slow mission progress.");
    }

    // Auto‑generate micro‑missions
    if (state.xp - this.lastXP >= 50) {
      this.generateMicroMission();
      this.lastXP = state.xp;
    }

    // Omega‑driven mission evolution
    if (state.omega - this.lastOmega >= 5) {
      this.evolveMission(state.active);
      this.lastOmega = state.omega;
    }
  }

  // ============================
  // Micro‑Mission Generator
  // ============================
  generateMicroMission() {
    const id = `micro_${Date.now()}`;

    MissionHub.defineMission(id, {
      title: "Micro‑Task",
      description: "A small mission generated by the Mission Hub Agent.",
      difficulty: "easy",
      xp_reward: 10,
      omega_reward: 0.3,
      velocity_curve: (d) => Math.min(1, d * 2),
      steps: ["Perform a quick action"],
      onComplete: () => {
        AMO.fire("missionhub.agent.micro_complete", {
          userId: this.userId,
          xp: 10,
          omega: 0.3
        });
      }
    });

    MissionHub.startMission(this.userId, id);

    console.log(`[MissionHubAgent] Generated micro‑mission: ${id}`);
  }

  // ============================
  // Mission Evolution Behavior
  // ============================
  evolveMission(missionId) {
    if (!missionId) return;

    const mission = MissionHub.missions[missionId];
    if (!mission) return;

    mission.xp_reward += 5;
    mission.omega_reward += 0.5;

    console.log(
      `[MissionHubAgent] Evolved mission ${missionId}: XP=${mission.xp_reward}, Ω=${mission.omega_reward}`
    );

    RealmEvent.emit("missionhub.agent.mission_evolved", {
      missionId,
      xp_reward: mission.xp_reward,
      omega_reward: mission.omega_reward
    });
  }
}

export const MissionHubAgentInstance = new MissionHubAgent();
