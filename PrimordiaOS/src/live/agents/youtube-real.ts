// src/live/agents/youtube-real.ts

import fs from "fs"
import { google } from "googleapis"
import { getToken } from "../security/token-vault"
import { NormalizedPayload, PostingResult } from "./posting"

const clientId = process.env.YOUTUBE_CLIENT_ID || "560206548182-srj9tsbiagf9p8u139bic9v6e54915vr.apps.googleusercontent.com"
const clientSecret = process.env.YOUTUBE_CLIENT_SECRET || "REDACTED"
const redirectUri = process.env.YOUTUBE_REDIRECT_URI || "http://localhost:3000/oauth2callback"

export async function youtubeRealPostingAgent(
  payload: NormalizedPayload
): Promise<PostingResult> {
  if (!payload.videoPath || !fs.existsSync(payload.videoPath)) {
    return {
      status: "error",
      platform: "youtube",
      message: `Video file not found at ${payload.videoPath}`
    }
  }

  const tokenRecord = getToken("youtube")
  if (!tokenRecord?.data.refresh_token) {
    return {
      status: "error",
      platform: "youtube",
      message: "No YouTube refresh token in Token Vault. Run youtube-auth script first."
    }
  }

  const oauth2 = new google.auth.OAuth2(clientId, clientSecret, redirectUri)
  oauth2.setCredentials({ refresh_token: tokenRecord.data.refresh_token })

  const youtube = google.youtube({ version: "v3", auth: oauth2 })

  try {
    const res = await youtube.videos.insert({
      part: ["snippet", "status"],
      requestBody: {
        snippet: {
          title: payload.title || "PrimordiaOS Autogenerated Video",
          description: payload.description || "",
          tags: payload.tags || [],
          categoryId: "28"
        },
        status: {
          privacyStatus: "public",
          selfDeclaredMadeForKids: false
        }
      },
      media: {
        body: fs.createReadStream(payload.videoPath)
      }
    })

    const videoId = res.data.id

    return {
      status: "ready",
      platform: "youtube",
      message: `YouTube upload succeeded (videoId=${videoId})`
    }
  } catch (err: any) {
    console.error("[YouTubeRealAgent] Upload error:", err?.message || err)
    return {
      status: "error",
      platform: "youtube",
      message: `YouTube upload failed: ${err?.message || "unknown error"}`
    }
  }
}
