                Write-Host ("  ||  {0}" -f $line.PadRight(60) + "  ||") -ForegroundColor White
            }
        }
    }

    Sep
    Row "Refreshed" (Get-Date -Format 'yyyy-MM-dd HH:mm:ss') 'DarkGray'
    Write-Host ("  " + ("=" * $W)) -ForegroundColor Cyan
    Write-Host ""
    Write-Host "  Type 'help' | 'hud' | 'diag' | 'prophecy' | 'agent spawn <name>'" -ForegroundColor DarkGray
    Write-Host ""
}

