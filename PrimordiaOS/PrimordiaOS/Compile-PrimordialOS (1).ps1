function Start-PrimordialAgent {
    <#
    .SYNOPSIS  Spawn a named agent.
    .EXAMPLE   Start-PrimordialAgent -Name "sentinel"
    .EXAMPLE   Start-PrimordialAgent -Name "bob" -Role "watcher"
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Name,
        [string]$Role     = 'executor',
        [hashtable]$Config = @{}
    )
    $key = $Name.ToLower()
    if ($script:AGENT_REGISTRY.Contains($key)) {
        Write-Host "  [AGENT] '$Name' already running." -ForegroundColor Yellow; return
    }
    $roleDesc = if ($script:AGENT_ROLES.Contains($Role)) { $script:AGENT_ROLES[$Role] } else { 'Custom' }
    $agent = [PSCustomObject]@{
        Name      = $Name;  Role      = $Role;  RoleDesc = $roleDesc
        Config    = $Config; Status   = 'RUNNING'
        StartTime = Get-Date; Cycles  = 0; LastPulse = Get-Date
    }
    $script:AGENT_REGISTRY[$key] = $agent
    Write-Host ("  [AGENT] Spawned: {0} — {1}" -f $Name, $roleDesc) -ForegroundColor Green
    return $agent
}

