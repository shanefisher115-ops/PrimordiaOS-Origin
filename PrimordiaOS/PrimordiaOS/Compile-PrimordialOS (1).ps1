function Get-CleanHeader {
    <#
    Read the existing .psm1 (if any), strip everything from the first strip-anchor
    onward, and return only the "hand-written preamble" lines as a string.
    If no file exists, returns an empty string.
    #>
    param([string]$FilePath)
    if (-not (Test-Path $FilePath)) { return '' }

    $lines      = Get-Content $FilePath -Encoding UTF8
    $cutIndex   = -1

    for ($i = 0; $i -lt $lines.Count; $i++) {
        foreach ($anchor in $STRIP_ANCHORS) {
            if ($lines[$i] -match [regex]::Escape($anchor)) {
                $cutIndex = $i
                break
            }
        }
        if ($cutIndex -ge 0) { break }
    }

    if ($cutIndex -le 0) {
        # Nothing to keep — the whole file is auto-generated or empty
        return ''
    }
    return ($lines[0..($cutIndex - 1)] -join "`n")
}

function Test-ScriptSyntax {
    <#
    Use the PowerShell AST parser to validate syntax without executing.
    Returns $true if clean, $false + prints errors otherwise.
    #>
    param([string]$FilePath)
    $errors  = $null
    $tokens  = $null
    [System.Management.Automation.Language.Parser]::ParseFile(
        $FilePath, [ref]$tokens, [ref]$errors) | Out-Null

    if ($errors.Count -gt 0) {
        $errors | ForEach-Object {
            Fail ("Syntax: Line {0} — {1}" -f $_.Extent.StartLineNumber, $_.Message)
        }
        return $false
    }
    return $true
}

