function Show-PrimordialDashboard {
    <#
    .SYNOPSIS  Full-width ASCII dashboard showing all OS subsystem vitals.
    .PARAMETER Compact  Omit per-agent and per-memory detail rows.
    #>
    [CmdletBinding()]
    param([switch]$Compact)

    $uptime  = (Get-Date) - $script:BOOT_TIME
    $upStr   = "{0:D2}h {1:D2}m {2:D2}s" -f [int]$uptime.TotalHours, $uptime.Minutes, $uptime.Seconds
    $memKeys = if ($script:PRIMORDIAL_MEMORY) { $script:PRIMORDIAL_MEMORY.Count } else { 0 }
    $agents  = if ($script:AGENT_REGISTRY)   { $script:AGENT_REGISTRY.Count    } else { 0 }
    $loops   = if ($script:LOOP_REGISTRY)    { $script:LOOP_REGISTRY.Count     } else { 0 }
    $routes  = $script:ROUTER_TABLE.Count
    $ps      = $PSVersionTable.PSVersion.ToString()

    $cpuLoad = try {
        $c = Get-CimInstance Win32_Processor -Property LoadPercentage -ErrorAction Stop
        "{0}%" -f ($c | Measure-Object LoadPercentage -Average).Average
    } catch { "N/A" }

    $ramInfo = try {
        $o = Get-CimInstance Win32_OperatingSystem -ErrorAction Stop
        "{0:N0} MB free / {1:N0} MB total" -f ($o.FreePhysicalMemory/1KB),($o.TotalVisibleMemorySize/1KB)
    } catch { "N/A" }

    Clear-Host
    $W = 66
    $pad = { param($s,$w) $s.PadRight($w).Substring(0,$w) }

    function Row([string]$label,[string]$val,[string]$color='White') {
        $content = "  {0,-14}: {1}" -f $label, $val
        Write-Host ("  ||  {0}" -f (& $pad $content 60) + "  ||") -ForegroundColor $color
    }
    function Sep { Write-Host ("  " + ("=" * $W)) -ForegroundColor DarkCyan }
    function Hdr([string]$title) {
        $t = "  ||  $title"
        Write-Host ($t.PadRight($W - 2) + "  ||") -ForegroundColor Magenta
    }

    Write-Host ""
    Write-Host ("  " + ("=" * $W)) -ForegroundColor Cyan
    $hdr = "  ||  P R I M O R D I A L  O S  --  D A S H B O A R D"
    Write-Host ($hdr.PadRight($W - 2) + "  ||") -ForegroundColor Cyan
    Sep

    Row "Version"    "v$script:PRIMORDIAL_VERSION"
    Row "Session"    $script:SESSION_ID
    Row "Uptime"     $upStr
    Row "PowerShell" $ps
    Sep
    Row "CPU Load"   $cpuLoad   'Yellow'
    Row "RAM"        $ramInfo   'Yellow'
    Sep
    Row "Mem Keys"   $memKeys   'Green'
    Row "Agents"     $agents    'Green'
    Row "Loops"      $loops     'Green'
    Row "Routes"     $routes    'Green'

    if (-not $Compact) {
        # Memory snapshot
        if ($script:PRIMORDIAL_MEMORY -and $script:PRIMORDIAL_MEMORY.Count -gt 0) {
            Sep; Hdr "MEMORY SNAPSHOT (top 5)"
            $script:PRIMORDIAL_MEMORY.GetEnumerator() | Select-Object -First 5 | ForEach-Object {
                $line = "    {0} = {1}" -f $_.Key, ($_.Value -as [string])
                if ($line.Length -gt 56) { $line = $line.Substring(0,53) + '...' }
                Write-Host ("  ||  {0}" -f $line.PadRight(60) + "  ||") -ForegroundColor White
            }
        }
        # Agent list
        if ($script:AGENT_REGISTRY -and $script:AGENT_REGISTRY.Count -gt 0) {
            Sep; Hdr "ACTIVE AGENTS"
            $script:AGENT_REGISTRY.GetEnumerator() | Select-Object -First 6 | ForEach-Object {
                $ag   = $_.Value
