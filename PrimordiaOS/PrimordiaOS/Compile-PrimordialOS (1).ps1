# REGION: HUD
# =============================================================================
function Show-PrimordialHUD {
    <#
    .SYNOPSIS  Flicker-free live HUD that updates in-place. Press Ctrl+C to exit.
    .PARAMETER RefreshSeconds  Refresh interval (default 3).
    .PARAMETER MaxCycles       Stop after N cycles; 0 = run forever.
    #>
    [CmdletBinding()]
    param([int]$RefreshSeconds = 3, [int]$MaxCycles = 0)

    Write-Host "  [HUD] Live feed started — Ctrl+C to quit" -ForegroundColor DarkCyan
    Start-Sleep -Milliseconds 300
    $cycle = 0

    try {
        while ($MaxCycles -eq 0 -or $cycle -lt $MaxCycles) {
            $cycle++
            $uptime  = (Get-Date) - $script:BOOT_TIME
            $upStr   = "{0:D2}:{1:D2}:{2:D2}" -f [int]$uptime.TotalHours,$uptime.Minutes,$uptime.Seconds
            $agents  = if ($script:AGENT_REGISTRY) { $script:AGENT_REGISTRY.Count } else { 0 }
            $loops   = if ($script:LOOP_REGISTRY)  { $script:LOOP_REGISTRY.Count  } else { 0 }
            $memKeys = if ($script:PRIMORDIAL_MEMORY) { $script:PRIMORDIAL_MEMORY.Count } else { 0 }
            $ts      = Get-Date -Format 'HH:mm:ss'
            $pulse   = if ($script:PROPHECY_ACTIVE) { '[PROPHECY ACTIVE]' } else { '' }

            $agentNames = if ($agents -gt 0) {
                ($script:AGENT_REGISTRY.Keys | Select-Object -First 5) -join ', '
            } else { '—' }

            $line1 = "  [HUD #{0:D4}]  {1}  UP:{2}  AGENTS:{3}  LOOPS:{4}  MEM:{5}  {6}" `
                        -f $cycle,$ts,$upStr,$agents,$loops,$memKeys,$pulse
            $line2 = "  AGENTS: $agentNames"

            # Overwrite in-place (no Clear-Host to avoid flicker)
            [Console]::SetCursorPosition(0, [Math]::Max(0,[Console]::CursorTop - 3))
            Write-Host $line1.PadRight(80) -ForegroundColor Green
            Write-Host $line2.PadRight(80) -ForegroundColor DarkGreen
            Write-Host ("  Session: $script:SESSION_ID  v$script:PRIMORDIAL_VERSION").PadRight(80) -ForegroundColor DarkGray

            Start-Sleep -Seconds $RefreshSeconds
        }
    } catch [System.Management.Automation.PipelineStoppedException] {
        Write-Host "`n  [HUD] Stopped." -ForegroundColor DarkCyan
    }
}

