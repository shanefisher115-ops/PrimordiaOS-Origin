function Invoke-ProphecyEngine {
    <#
    .SYNOPSIS  Query the oracle. Returns thematic system wisdom anchored to an optional topic.
    .EXAMPLE   Invoke-ProphecyEngine -Query "memory"
    #>
    [CmdletBinding()]
    param([string]$Query = '')
    $script:PROPHECY_ACTIVE = $true

    $oracle = if ($Query) {
        $kw = ($Query -split '\s+')[0]
        $hits = $script:PROPHECY_ORACLES | Where-Object { $_ -match [regex]::Escape($kw) }
        if ($hits) { $hits | Get-Random } else { $script:PROPHECY_ORACLES | Get-Random }
    } else { $script:PROPHECY_ORACLES | Get-Random }

    $entry = [PSCustomObject]@{
        CycleID   = $script:PROPHECY_HISTORY.Count + 1
        Timestamp = Get-Date
        Query     = $Query
        Oracle    = $oracle
    }
    $script:PROPHECY_HISTORY.Add($entry)

    Write-Host ""
    Write-Host "  ooooooooooooooooooooooooooooooooooooooo" -ForegroundColor Magenta
    Write-Host ("  o  PROPHECY #{0}" -f $entry.CycleID) -ForegroundColor Magenta
    if ($Query) { Write-Host "  o  Topic: $Query" -ForegroundColor DarkMagenta }
    Write-Host ""
    Write-Host "  o  $oracle" -ForegroundColor White
    Write-Host ""
    Write-Host "  ooooooooooooooooooooooooooooooooooooooo" -ForegroundColor Magenta
    Write-Host ""

    $script:PROPHECY_ACTIVE = $false
    return $entry
}

