$script:ROUTER_TABLE = [ordered]@{}

function Register-PrimordialRoute {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Command,
        [Parameter(Mandatory)][scriptblock]$Handler,
        [string]$Description = ''
    )
    $script:ROUTER_TABLE[$Command.ToLower()] = [PSCustomObject]@{
        Command     = $Command
        Handler     = $Handler
        Description = $Description
        Registered  = Get-Date
    }
}

function Invoke-PrimordialRouter {
    <#
    .SYNOPSIS  Route a command string to its registered handler.
    .EXAMPLE   Invoke-PrimordialRouter "agent spawn sentinel"
    .EXAMPLE   "prophecy loops" | Invoke-PrimordialRouter
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory,ValueFromPipeline)][string]$InputLine)
    $tokens = $InputLine.Trim() -split '\s+', 2
    $cmd    = $tokens[0].ToLower()
    $args   = if ($tokens.Count -gt 1) { $tokens[1] } else { '' }
    if ($script:ROUTER_TABLE.Contains($cmd)) {
        try   { & $script:ROUTER_TABLE[$cmd].Handler $args }
        catch { Write-Host "  [ROUTER ERR] $cmd -- $_" -ForegroundColor Red }
    } else {
        Write-Host "  [?] Unknown command: '$cmd'  (type 'help' for list)" -ForegroundColor Yellow
    }
}

