$script:PRIMORDIAL_MEMORY = [ordered]@{}

function Set-PrimordialMemory {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Key,
        [Parameter(Mandatory)][object]$Value,
        [switch]$Persist
    )
    $script:PRIMORDIAL_MEMORY[$Key] = $Value
    Write-Host "  [MEM] $Key <- $Value" -ForegroundColor DarkGreen
    if ($Persist) {
        $dir = Join-Path $PSScriptRoot '.primordial_mem'
        if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
        $Value | ConvertTo-Json -Depth 10 | Set-Content (Join-Path $dir "$Key.json") -Encoding UTF8 -Force
    }
}

function Get-PrimordialMemory {
    [CmdletBinding()]
    param([string]$Key, [switch]$ListAll, [object]$Default)
    if ($ListAll) {
        if ($script:PRIMORDIAL_MEMORY.Count -eq 0) {
            Write-Host "  [MEM] Memory store is empty." -ForegroundColor Yellow; return
        }
        Write-Host "`n  == MEMORY STORE ==" -ForegroundColor Cyan
        $script:PRIMORDIAL_MEMORY.GetEnumerator() |
            ForEach-Object { Write-Host ("  {0,-30} = {1}" -f $_.Key, $_.Value) -ForegroundColor White }
        Write-Host ""
        return
    }
    if ($script:PRIMORDIAL_MEMORY.Contains($Key)) { return $script:PRIMORDIAL_MEMORY[$Key] }
    return $Default
}

function Clear-PrimordialMemory {
    [CmdletBinding(SupportsShouldProcess)]
    param([string]$Key)
    if ($Key) {
        if ($PSCmdlet.ShouldProcess($Key,'Remove memory key')) {
            $script:PRIMORDIAL_MEMORY.Remove($Key)
            Write-Host "  [MEM] Removed: $Key" -ForegroundColor Yellow
        }
    } else {
        if ($PSCmdlet.ShouldProcess('ALL','Clear memory')) {
            $script:PRIMORDIAL_MEMORY.Clear()
            Write-Host "  [MEM] Memory cleared." -ForegroundColor Yellow
        }
    }
}

function Export-PrimordialMemory {
    [CmdletBinding()]
    param([string]$Path = (Join-Path $PSScriptRoot 'PrimordialMemory.json'))
    $script:PRIMORDIAL_MEMORY | ConvertTo-Json -Depth 10 |
        Set-Content -Path $Path -Encoding UTF8 -Force
    Write-Host "  [MEM] Exported -> $Path" -ForegroundColor Green
}

function Import-PrimordialMemory {
    [CmdletBinding()]
    param([string]$Path = (Join-Path $PSScriptRoot 'PrimordialMemory.json'))
    if (Test-Path $Path) {
        (Get-Content $Path -Raw | ConvertFrom-Json).PSObject.Properties |
            ForEach-Object { $script:PRIMORDIAL_MEMORY[$_.Name] = $_.Value }
        Write-Host "  [MEM] Imported $($script:PRIMORDIAL_MEMORY.Count) keys from $Path" -ForegroundColor Green
    } else {
        Write-Host "  [MEM] File not found: $Path" -ForegroundColor Yellow
    }
}

