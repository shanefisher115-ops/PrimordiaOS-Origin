.SYNOPSIS
    PrimordialOS Master Compiler v1.0
    Scans, repairs, injects, and reloads PrimordialOS.psm1 into a unified working state.

.DESCRIPTION
    This compiler:
      1. Locates or bootstraps PrimordialOS.psm1
      2. Backs up the original
      3. Strips corrupted / duplicate bottom sections
      4. Injects canonical blocks: Diagnostic, Router, Dashboard,
         Memory, HUD, Prophecy, Agents, and Event Loops
      5. Validates syntax via PowerShell AST parser
      6. Reloads the module into the current session
      7. Runs a post-load diagnostic and prints the dashboard

.USAGE
    # Run from any PowerShell 5.1+ or pwsh session:
    .\Compile-PrimordialOS.ps1

    # Override the module path:
    $env:PRIMORDIAL_HOME = "C:\MyPath\PrimordialOS"
    .\Compile-PrimordialOS.ps1

    # Skip auto-reload (just build the file):
    .\Compile-PrimordialOS.ps1 -NoReload

    # Dry run (show what would happen, write nothing):
    .\Compile-PrimordialOS.ps1 -WhatIf
#>

