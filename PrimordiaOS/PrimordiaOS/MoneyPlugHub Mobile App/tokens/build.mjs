import StyleDictionary from "style-dictionary";
// ── Tailwind v4 @theme formatter ────────────────────────────────────────────
// Maps semantic tokens → Tailwind v4 CSS custom property conventions so that
// classes like bg-bg-primary, rounded-card, shadow-glow, p-layout etc. resolve.
const TW_SEMANTIC_COLORS = {
    "semantic-color-background-primary": "color-bg-primary",
    "semantic-color-background-card": "color-bg-card",
    "semantic-color-text-primary": "color-text-primary",
    "semantic-color-text-secondary": "color-text-secondary",
    "semantic-color-border-subtle": "color-border-subtle",
    "semantic-color-accent-primary": "color-accent-primary",
    "semantic-color-accent-secondary": "color-accent-secondary",
    "semantic-color-success": "color-success",
};
const TW_SEMANTIC_RADIUS = {
    "semantic-radius-card": "radius-card",
    "semantic-radius-button": "radius-button",
    "semantic-radius-input": "radius-input",
};
const TW_SEMANTIC_SPACING = {
    "semantic-spacing-layout-padding": "spacing-layout",
    "semantic-spacing-section-gap": "spacing-section",
    "semantic-spacing-stack-gap": "spacing-stack",
};
const TW_SEMANTIC_SHADOW = {
    "semantic-shadow-card": "shadow-card",
    "semantic-shadow-glow": "shadow-glow",
};
const TW_SEMANTIC_TYPOGRAPHY = {
    "semantic-typography-display": "text-display",
    "semantic-typography-title": "text-title",
    "semantic-typography-section-title": "text-section",
    "semantic-typography-body": "text-body",
    "semantic-typography-caption": "text-caption",
};
const ALL_TW_MAPS = [
    TW_SEMANTIC_COLORS,
    TW_SEMANTIC_RADIUS,
    TW_SEMANTIC_SPACING,
    TW_SEMANTIC_SHADOW,
    TW_SEMANTIC_TYPOGRAPHY,
];
function sdNameToKey(token) {
    return token.name.replace(/_/g, "-");
}
StyleDictionary.registerFormat({
    name: "tailwind/v4-theme",
    format: ({ dictionary }) => {
        const lines = [
            "/* Auto-generated by Style Dictionary — do not edit */",
            "@theme {",
        ];
        for (const token of dictionary.allTokens) {
            const key = sdNameToKey(token);
            for (const map of ALL_TW_MAPS) {
                if (map[key]) {
                    lines.push(`  --${map[key]}: ${token.value};`);
                }
            }
        }
        lines.push("}");
        return lines.join("\n") + "\n";
    },
});
// ── Style Dictionary config ──────────────────────────────────────────────────
const sd = new StyleDictionary({
    source: ["tokens/**/*.json"],
    platforms: {
        // Tailwind v4 @theme block (primary web output)
        tailwind: {
            transformGroup: "css",
            buildPath: "build/css/",
            files: [
                {
                    destination: "tailwind-theme.css",
                    format: "tailwind/v4-theme",
                },
            ],
        },
        // Full CSS custom properties (all tokens, for reference / non-Tailwind use)
        css: {
            transformGroup: "css",
            buildPath: "build/css/",
            files: [
                {
                    destination: "variables.css",
                    format: "css/variables",
                    options: { outputReferences: true, selector: ":root" },
                },
            ],
        },
        // JavaScript ES6 named exports
        js: {
            transformGroup: "js",
            buildPath: "build/js/",
            files: [{ destination: "tokens.js", format: "javascript/es6" }],
        },
        // iOS Objective-C macros
        ios: {
            transformGroup: "ios",
            buildPath: "build/ios/",
            files: [{ destination: "tokens.h", format: "ios/macros" }],
        },
        // Android XML resources
        android: {
            transformGroup: "android",
            buildPath: "build/android/",
            files: [{ destination: "tokens.xml", format: "android/resources" }],
        },
    },
});
await sd.buildAllPlatforms();
