/**
 * Style Dictionary build — run with:
 *   pnpm build:tokens
 *
 * Outputs:
 *   src/styles/theme.css    — CSS custom properties (:root { --primitive-*, --semantic-*, --component-* })
 *   src/styles/tailwind.css — Tailwind v4 @theme block (token → Tailwind utility mapping)
 */
import StyleDictionary from "style-dictionary";
// ── Helpers ──────────────────────────────────────────────────────────────────
function sdName(token) {
    return token.name.replace(/_/g, "-");
}
// ── Semantic → Tailwind v4 utility name map ──────────────────────────────────
const TW_MAP = {
    // Colors
    "semantic-color-background-primary": "color-bg-primary",
    "semantic-color-background-card": "color-bg-card",
    "semantic-color-text-primary": "color-text-primary",
    "semantic-color-text-secondary": "color-text-secondary",
    "semantic-color-border-subtle": "color-border-subtle",
    "semantic-color-accent-primary": "color-accent-primary",
    "semantic-color-accent-secondary": "color-accent-secondary",
    "semantic-color-success": "color-success",
    // Radius
    "semantic-radius-card": "radius-card",
    "semantic-radius-button": "radius-button",
    "semantic-radius-input": "radius-input",
    // Spacing
    "semantic-spacing-layout-padding": "spacing-layout",
    "semantic-spacing-section-gap": "spacing-section",
    "semantic-spacing-stack-gap": "spacing-stack",
    // Shadows
    "semantic-shadow-card": "shadow-card",
    "semantic-shadow-glow": "shadow-glow",
    // Typography
    "semantic-typography-display": "text-display",
    "semantic-typography-title": "text-title",
    "semantic-typography-section-title": "text-section",
    "semantic-typography-body": "text-body",
    "semantic-typography-caption": "text-caption",
};
// ── Custom format: Tailwind v4 @theme block ──────────────────────────────────
StyleDictionary.registerFormat({
    name: "tailwind/v4-theme",
    format: ({ dictionary }) => {
        const header = [
            "/**",
            " * Tailwind v4 @theme block — auto-generated by Style Dictionary.",
            " * Do not edit directly. Run `pnpm build:tokens` to regenerate.",
            " */",
        ].join("\n");
        const lines = [];
        for (const token of dictionary.allTokens) {
            const key = sdName(token);
            const twKey = TW_MAP[key];
            if (twKey)
                lines.push(`  --${twKey}: ${token.value};`);
        }
        return `${header}\n\n@theme {\n${lines.join("\n")}\n}\n`;
    },
});
// ── Custom format: CSS variables with file header ────────────────────────────
StyleDictionary.registerFormat({
    name: "css/variables-with-header",
    format: ({ dictionary, options }) => {
        const selector = options.selector ?? ":root";
        const header = [
            "/**",
            " * CSS custom properties — auto-generated by Style Dictionary.",
            " * Do not edit directly. Run `pnpm build:tokens` to regenerate.",
            " */",
        ].join("\n");
        const lines = [];
        for (const token of dictionary.allTokens) {
            const key = sdName(token);
            // outputReferences: emit var() when the token references another token
            const value = token.original.value &&
                typeof token.original.value === "string" &&
                token.original.value.startsWith("{")
                ? `var(--${sdName({ ...token, name: token.original.value.slice(1, -1).replace(/\./g, "-") })})`
                : token.value;
            lines.push(`  --${key}: ${value};`);
        }
        return `${header}\n\n${selector} {\n${lines.join("\n")}\n}\n`;
    },
});
// ── Config ───────────────────────────────────────────────────────────────────
const config = {
    source: ["tokens/**/*.json"],
    platforms: {
        // 1. CSS custom properties → src/styles/theme.css
        css: {
            transformGroup: "css",
            buildPath: "src/styles/",
            files: [
                {
                    destination: "theme.css",
                    format: "css/variables-with-header",
                    options: { outputReferences: true, selector: ":root" },
                },
            ],
        },
        // 2. Tailwind v4 @theme block → src/styles/tailwind.css
        tailwind: {
            transformGroup: "css",
            buildPath: "src/styles/",
            files: [
                {
                    destination: "tailwind.css",
                    format: "tailwind/v4-theme",
                },
            ],
        },
        // 3. JS ES6 named exports (for JS consumers)
        js: {
            transformGroup: "js",
            buildPath: "build/js/",
            files: [{ destination: "tokens.js", format: "javascript/es6" }],
        },
        // 4. iOS Objective-C macros
        ios: {
            transformGroup: "ios",
            buildPath: "build/ios/",
            files: [{ destination: "tokens.h", format: "ios/macros" }],
        },
        // 5. Android XML resources
        android: {
            transformGroup: "android",
            buildPath: "build/android/",
            files: [{ destination: "tokens.xml", format: "android/resources" }],
        },
    },
};
// ── Run ──────────────────────────────────────────────────────────────────────
const sd = new StyleDictionary(config);
await sd.buildAllPlatforms();
