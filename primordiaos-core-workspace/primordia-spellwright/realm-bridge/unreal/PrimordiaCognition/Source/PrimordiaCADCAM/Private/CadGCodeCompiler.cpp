namespace
{
	FCadMove MakeParsedMove(ECadMoveType Type, const FVector& Position, double Feed)
	{
		FCadMove M;
		M.Type = Type;
		M.Position = Position;
		M.Feed = Feed;
		return M;
	}
}

FString FCadGCodeCompiler::Num(double V) const
{
	const double Scale = FMath::Pow(10.0, Options.Decimals);
	double R = FMath::RoundToDouble(V * Scale) / Scale;
	if (R == 0.0)
	{
		R = 0.0; // no "-0.000"
	}
	return FString::Printf(TEXT("%.*f"), Options.Decimals, R);
}

FString FCadGCodeCompiler::SanitizeComment(const FString& Text)
{
	FString Out;
	for (const TCHAR C : Text.ToUpper())
	{
		Out.AppendChar((C == '(' || C == ')' || C == ';' || C == '%' || C < 32 || C > 126) ? TCHAR(' ') : C);
	}
	return Out.TrimStartAndEnd();
}

FString FCadGCodeCompiler::Compile(const FCadPart& Part, const FCadToolpath& Path, double EstimatedSeconds) const
{
	TArray<FString> Lines;
	int32 LineNo = 0;
	auto Emit = [&](const FString& Line)
	{
		if (Options.bLineNumbers && !Line.StartsWith(TEXT("(")) && !Line.StartsWith(TEXT("%")))
		{
			LineNo += Options.LineNumberStep;
			Lines.Add(FString::Printf(TEXT("N%d %s"), LineNo, *Line));
		}
		else
		{
			Lines.Add(Line);
		}
	};
	auto Comment = [&](const FString& Text)
	{
		if (Options.bComments)
		{
			Lines.Add(FString::Printf(TEXT("(%s)"), *SanitizeComment(Text)));
		}
	};

	const FCadTool& Tool = Path.Tool;
	Lines.Add(TEXT("%"));
	const bool bGrbl = Options.Dialect == ECadGCodeDialect::Grbl;
	const FString Title = SanitizeComment(FString::Printf(TEXT("PRIMORDIA %s"), *Part.Name.ToString()));
	Lines.Add(bGrbl ? FString::Printf(TEXT("(%s)"), *Title) : FString::Printf(TEXT("O%04d (%s)"), Options.ProgramNumber, *Title));
	Comment(FString::Printf(TEXT("GENERATED BY PRIMORDIAOS CADCAM %s"), *FDateTime::UtcNow().ToIso8601()));
	Comment(FString::Printf(TEXT("STOCK %s X %s X %s MM %s"), *Num(Part.Stock.Size.X), *Num(Part.Stock.Size.Y), *Num(Part.Stock.Size.Z), *Part.Stock.Material));
	Comment(TEXT("ORIGIN X0 Y0 AT STOCK FRONT LEFT CORNER, Z0 AT STOCK TOP"));
	Comment(FString::Printf(TEXT("T%d D%s FLAT END MILL, %d FEATURES"), Tool.Number, *Num(Tool.Diameter), Part.Features.Num()));
	if (EstimatedSeconds > 0.0)
	{
		Comment(FString::Printf(TEXT("ESTIMATED CYCLE TIME %.1f MIN"), EstimatedSeconds / 60.0));
	}
	Emit(bGrbl ? TEXT("G21 G90 G94 G17") : TEXT("G21 G90 G94 G17 G40 G49 G80"));
	if (bGrbl)
	{
		Lines.Add(FString::Printf(TEXT("(LOAD TOOL %d BEFORE STARTING)"), Tool.Number));
	}
	else
	{
		Emit(FString::Printf(TEXT("T%d M06"), Tool.Number));
	}
	Emit(FString::Printf(TEXT("S%d M03"), FMath::RoundToInt(Tool.SpindleRpm)));
	if (Options.SpindleWarmupSeconds > 0.0)
	{
		Emit(FString::Printf(TEXT("%s P%s"), bGrbl ? TEXT("G4") : TEXT("G04"), *Num(Options.SpindleWarmupSeconds)));
	}
	if (Options.bCoolant)
	{
		Emit(TEXT("M08"));
	}

	int32 Modal = -1;
	double Feed = -1.0;
	FVector Pos(TNumericLimits<double>::Max());
	for (const FCadMove& M : Path.Moves)
	{
		const int32 G = M.Type == ECadMoveType::Rapid ? 0 : 1;
		TArray<FString> AxisWords;
		auto Axis = [&](TCHAR Letter, double New, double Old)
		{
			const FString Text = Num(New);
			if (Old == TNumericLimits<double>::Max() || Num(Old) != Text)
			{
				AxisWords.Add(FString::Printf(TEXT("%c%s"), Letter, *Text));
			}
		};
		Axis('X', M.Position.X, Pos.X);
		Axis('Y', M.Position.Y, Pos.Y);
		Axis('Z', M.Position.Z, Pos.Z);
		if (AxisWords.Num() == 0)
		{
			continue; // no motion at the program's resolution
		}
		Pos = M.Position;

		FString Words;
		if (G != Modal)
		{
			Words = G == 0 ? TEXT("G00 ") : TEXT("G01 ");
			Modal = G;
		}
		Words += FString::Join(AxisWords, TEXT(" "));
		if (G == 1 && !FMath::IsNearlyEqual(M.Feed, Feed))
		{
			Words += FString::Printf(TEXT(" F%d"), FMath::RoundToInt(M.Feed));
			Feed = M.Feed;
		}
		Emit(Words);
	}

	if (Options.bCoolant)
	{
		Emit(TEXT("M09"));
	}
	Emit(TEXT("M05"));
	Emit(FString::Printf(TEXT("G00 Z%s"), *Num(Path.SafeZ)));
	Emit(TEXT("M30"));
	Lines.Add(TEXT("%"));
	return FString::Join(Lines, TEXT("\n")) + TEXT("\n");
}

FCadGCodeParseResult FCadGCodeCompiler::Parse(const FString& Program, double SafeZ)
{
	FCadGCodeParseResult R;
	TArray<FString> Lines;
	Program.ParseIntoArrayLines(Lines, false);

	FVector Pos(0, 0, SafeZ);
	int32 Motion = 0;
	double Feed = 0.0;
	bool bAbsolute = true;
	double UnitScale = 1.0;
	R.Moves.Add(MakeParsedMove(ECadMoveType::Rapid, Pos, 0.0));

	for (int32 L = 0; L < Lines.Num() && !R.bEnded; ++L)
	{
		// Strip comments: (...) anywhere, ';' to end of line.
		FString Line;
		int32 Depth = 0;
		for (const TCHAR C : Lines[L])
		{
			if (C == '(') { ++Depth; continue; }
			if (C == ')') { Depth = FMath::Max(0, Depth - 1); continue; }
			if (C == ';' && Depth == 0) { break; }
			if (Depth == 0) { Line.AppendChar(FChar::ToUpper(C)); }
		}
		Line.TrimStartAndEndInline();
		if (Line.IsEmpty() || Line == TEXT("%"))
		{
			continue;
		}

		// Tokenize into letter + number words (spaces optional: "G1X10Y5" works).
		TArray<TPair<TCHAR, double>> Words;
		int32 i = 0;
		while (i < Line.Len())
		{
			const TCHAR Letter = Line[i];
			if (FChar::IsWhitespace(Letter)) { ++i; continue; }
			if (!FChar::IsAlpha(Letter))
			{
				R.Errors.Add(FString::Printf(TEXT("line %d: unexpected '%c'"), L + 1, Letter));
				break;
			}
			int32 j = i + 1;
			while (j < Line.Len() && (FChar::IsDigit(Line[j]) || Line[j] == '.' || Line[j] == '-' || Line[j] == '+' || FChar::IsWhitespace(Line[j])))
			{
				if (FChar::IsWhitespace(Line[j]) && j + 1 < Line.Len() && FChar::IsAlpha(Line[j + 1])) { break; }
				++j;
			}
			const FString NumText = Line.Mid(i + 1, j - i - 1).Replace(TEXT(" "), TEXT(""));
			if (NumText.IsEmpty() || !FCString::IsNumeric(*NumText))
			{
				R.Errors.Add(FString::Printf(TEXT("line %d: '%c' has no number"), L + 1, Letter));
				break;
			}
			Words.Emplace(Letter, FCString::Atod(*NumText));
			i = j;
		}

		bool bHasAxis = false;
		FVector Target = Pos;
		for (const TPair<TCHAR, double>& W : Words)
		{
			const int32 Code = FMath::RoundToInt(W.Value);
			switch (W.Key)
			{
			case 'G':
				if (Code == 0 || Code == 1) { Motion = Code; }
				else if (Code == 20) { UnitScale = 25.4; }
				else if (Code == 21) { UnitScale = 1.0; }
				else if (Code == 90) { bAbsolute = true; }
				else if (Code == 91) { bAbsolute = false; }
				else if (Code == 2 || Code == 3) { R.Errors.Add(FString::Printf(TEXT("line %d: arcs (G%d) are not supported"), L + 1, Code)); }
				break;
			case 'X': Target.X = bAbsolute ? W.Value * UnitScale : Target.X + W.Value * UnitScale; bHasAxis = true; break;
			case 'Y': Target.Y = bAbsolute ? W.Value * UnitScale : Target.Y + W.Value * UnitScale; bHasAxis = true; break;
			case 'Z': Target.Z = bAbsolute ? W.Value * UnitScale : Target.Z + W.Value * UnitScale; bHasAxis = true; break;
			case 'F': Feed = W.Value * UnitScale; break;
			case 'S': R.SpindleRpm = W.Value; break;
			case 'T': R.ToolNumber = Code; break;
			case 'M': if (Code == 30 || Code == 2) { R.bEnded = true; } break;
			default: break; // N, O, P and others carry no motion
			}
		}
		if (bHasAxis)
		{
			ECadMoveType Type = ECadMoveType::Rapid;
			if (Motion == 1)
			{
				const bool bZOnly = FMath::IsNearlyEqual(Target.X, Pos.X) && FMath::IsNearlyEqual(Target.Y, Pos.Y) && Target.Z < Pos.Z;
				Type = bZOnly ? ECadMoveType::Plunge : ECadMoveType::Feed;
				if (Feed <= 0.0)
				{
					R.Errors.Add(FString::Printf(TEXT("line %d: feed move without a feed rate"), L + 1));
				}
			}
			R.Moves.Add(MakeParsedMove(Type, Target, Motion == 1 ? Feed : 0.0));
			Pos = Target;
		}
	}
	if (!R.bEnded)
	{
		R.Errors.Add(TEXT("program has no M30/M02 end"));
	}
	return R;
}
